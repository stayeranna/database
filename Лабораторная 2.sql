create table Actor(
id smallint identity(1,1) primary key,
fullname nvarchar(50) not null
)
create table Performance(
id smallint identity(1,1) primary key,
[name] nvarchar(200) not null,
duration smallint not null check(duration >= 0 and duration < 1000),
[number of intervals] tinyint default(0) check([number of intervals] >= 0 and [number of intervals] < 10),
genre nvarchar(200),
director nvarchar(50)
)
create table Playbill(
[date] date,
[time] time,
primary key(date, time),
[number of vacant seats] smallint not null,
performanceId smallint not null foreign key references Performance(id),
[price coefficient] decimal not null default (1) check([price coefficient] > 0),
revenue decimal(15, 2)
)
create table Participation(
actorId smallint foreign key references Actor(id),
performanceId smallint foreign key references Performance(id),
primary key(actorId, performanceId),
[role] nvarchar(50)
)
create table [Type of seats](
id tinyint identity(1, 1) primary key,
[type] nvarchar(30) not null,
[number of seats] smallint not null check([number of seats] >= 0),
[basic price] decimal(7, 2) not null check([basic price] > 0)
)
create table Ticket(
id smallint identity(1, 1) primary key,
typeId tinyint not null foreign key references [Type of seats](id),
[row] tinyint not null check(row > 0),
seat tinyint not null check(seat > 0),
[price coefficient] decimal(9, 2) not null default (1)
)
create table Sale(
[performance date] date,
[performance time] time,
foreign key ([performance date], [performance time]) references Playbill([date], [time]),
ticketId smallint foreign key references Ticket(id),
primary key([performance date],[performance time], ticketId),
[is sold] bit default(0)
)




